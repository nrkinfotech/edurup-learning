async function seed() {
  try {
    await connectDB();
    console.log('Connected to MongoDB Atlas...');
    await InternshipPosting.deleteMany({});
    console.log('Cleared existing internship postings.');

    const docs = await InternshipPosting.insertMany(postings);
    console.log(`Successfully seeded ${docs.length} internship postings!`);

    const total = await InternshipPosting.countDocuments();
    const active = await InternshipPosting.countDocuments({ status: 'Active' });
    const inReview = await InternshipPosting.countDocuments({ status: 'In Review' });
    const closed = await InternshipPosting.countDocuments({ status: 'Closed' });
    const drafts = await InternshipPosting.countDocuments({ status: 'Draft' });

    console.log(`KPI Summary: Total: ${total}, Active: ${active} (${Math.round((active/total)*100)}%), In Review: ${inReview} (${Math.round((inReview/total)*100)}%), Closed: ${closed} (${Math.round((closed/total)*100)}%), Drafts: ${drafts} (${Math.round((drafts/total)*100)}%)`);

    process.exit(0);
  } catch (err) {
    console.error('Error seeding internship postings:', err);
    process.exit(1);
  }
}

seed();
